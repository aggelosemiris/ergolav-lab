// Συγκρούσεις αντιστοίχισης στον κατάλογο: λέξη με δύο σημασίες δεν γίνεται σιωπηλά λάθος είδος,
// και φράση-προϊόν με «μπάνιου»/«κουζίνας» δεν γίνεται τίτλος.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { parse } from '../src/parse.js';

const ids = t => parse(t).lines.map(l => l.id);
// Γραμμή εκτός καταλόγου που κρατιέται ως προϊόν (keep): [όνομα, ποσότητα, μονάδα].
const kept = t => parse(t).lines.filter(l => l.unknown && l.keep).map(l => [l.name, l.qty, l.unit]);

test('1 «ντουλάπι / ντουλάπα» χωρίς μπάνιο δεν είναι έπιπλο μπάνιου', () => {
  for(const [t, name, qty] of [
    ['ντουλάπι κουζίνας', 'Ντουλάπι κουζίνας', 1],
    ['δύο ντουλάπια κουζίνας', 'Ντουλάπια κουζίνας', 2],
    ['ντουλάπα υπνοδωματίου', 'Ντουλάπα υπνοδωματίου', 1],
    ['ντουλάπα ρούχων δίφυλλη', 'Ντουλάπα ρούχων δίφυλλη', 1],
    ['κρεμαστό ντουλάπι', 'Κρεμαστό ντουλάπι', 1],
    ['3 ντουλάπια πάνω από τον πάγκο', 'Ντουλάπια πάνω από τον πάγκο', 3],
    ['έπιπλο κουζίνας', 'Έπιπλο κουζίνας', 1],
  ]){
    const r = parse(t);
    assert.deepEqual(r.lines.map(l => l.id), ['unknown'], t);
    assert.deepEqual(kept(t), [[name, qty, 'τεμ.']], t);
    assert.equal(r.title, '', `${t}: δεν είναι τίτλος`);
  }
});

test('1 έλεγχος: ντουλάπι με μπάνιο / νιπτήρα μένει έπιπλο μπάνιου', () => {
  for(const t of ['ντουλάπι μπάνιου', 'ντουλάπι νιπτήρα', 'νιπτήρας με ντουλάπι', 'ντουλάπι μπάνιου με νιπτήρα', 'έπιπλο μπάνιου', 'έπιπλο', 'νιπτήρας με έπιπλο']){
    assert.deepEqual(ids(t), ['vanity'], t);
  }
  const v = parse('ντουλάπι μπάνιου 100 εκατοστά').lines[0];
  assert.deepEqual([v.id, v.name], ['vanity', 'Έπιπλο μπάνιου με νιπτήρα 100 εκ.']);
});

test('2 «γωνίες στήριξης» / γωνίες για ράφι δεν είναι γωνία πολυστρωματική', () => {
  for(const [t, name, qty] of [
    ['γωνίες στήριξης', 'Γωνίες στήριξης', 1],
    ['4 γωνιές στήριξης για ράφι', 'Γωνιές στήριξης για ράφι', 4],
    ['μεταλλικές γωνίες', 'Μεταλλικές γωνίες', 1],
    ['γωνίες για ράφια', 'Γωνίες για ράφια', 1],
    ['δύο γωνίες ραφιού', 'Γωνίες ραφιού', 2],
    ['6 σιδερένιες γωνίες', 'Σιδερένιες γωνίες', 6],
    ['γωνία στήριξης ντουλαπιού', 'Γωνία στήριξης ντουλαπιού', 1],
    ['γωνίες αλουμινίου', 'Γωνίες αλουμινίου', 1],
  ]){
    assert.deepEqual(ids(t), ['unknown'], t);
    assert.deepEqual(kept(t), [[name, qty, 'τεμ.']], t);
  }
});

test('2 έλεγχος: γωνίες υδραυλικών μένουν γωνία πολυστρωματική', () => {
  for(const t of ['6 γωνίες', '4 γωνάκια φ26', 'γωνίες φ20', '12 μέτρα σωλήνα πολυστρωματικό Φ20, 6 γωνίες', 'γωνία για τον σωλήνα']){
    assert.ok(ids(t).includes('elbow'), t);
  }
  assert.deepEqual(ids('γωνιακός διακόπτης'), ['valve']);
});

test('3 φράση-προϊόν με «μπάνιου» / «κουζίνας» μένει γραμμή, όχι τίτλος', () => {
  for(const [t, name] of [
    ['καθρέφτης μπάνιου', 'Καθρέφτης μπάνιου'],
    ['πάγκος κουζίνας', 'Πάγκος κουζίνας'],
    ['αξεσουάρ μπάνιου', 'Αξεσουάρ μπάνιου'],
    ['απορροφητήρας κουζίνας', 'Απορροφητήρας κουζίνας'],
    ['χαλάκι μπάνιου', 'Χαλάκι μπάνιου'],
    ['ντουλάπια κουζίνας', 'Ντουλάπια κουζίνας'],
  ]){
    const r = parse(t);
    assert.equal(r.title, '', `${t}: δεν είναι τίτλος`);
    assert.deepEqual(kept(t), [[name, 1, 'τεμ.']], t);
  }
});

test('3 έλεγχος: η περιγραφή της δουλειάς μένει τίτλος', () => {
  for(const [t, title] of [
    ['Ανακαίνιση μπάνιου', 'ανακαίνιση μπάνιου'],
    ['επισκευή κουζίνας στη Νέα Σμύρνη για τον Γιώργο', 'επισκευή κουζίνας'],
    ['αντικατάσταση πάγκου κουζίνας', 'αντικατάσταση πάγκου κουζίνας'],
    ['μπάνιο', 'μπάνιο'],
    ['κουζίνα', 'κουζίνα'],
    ['μπάνιο ξενώνα', 'μπάνιο ξενώνα'],
  ]){
    const r = parse(t);
    assert.equal(r.title, title, t);
    assert.deepEqual(kept(t), [], t);
  }
  // Η σειρά δεν αλλάζει τίποτα: το προϊόν γραμμή, η δουλειά τίτλος.
  for(const t of ['ανακαίνιση μπάνιου. καθρέφτης μπάνιου', 'καθρέφτης μπάνιου. ανακαίνιση μπάνιου']){
    const r = parse(t);
    assert.equal(r.title, 'ανακαίνιση μπάνιου', t);
    assert.deepEqual(kept(t), [['Καθρέφτης μπάνιου', 1, 'τεμ.']], t);
  }
});
