// Το άρθρο στο {είδος} των γενικών κατηγοριών: «Στερεώνουμε {είδος} στον τοίχο» → «Στερεώνουμε τις σίτες στον τοίχο».
// Βγαίνει από την κατάληξη της πρώτης λέξης (συνήθως το ουσιαστικό ή επίθετό του), μετά από κανονικοποίηση.
// Ό,τι μαντεύει λάθος, ο μάστορας το αλλάζει με ένα πάτημα και η επιλογή του μένει στη βιβλιοθήκη του.

export const ARTICLES = ['τον', 'την', 'το', 'τους', 'τις', 'τα'];
const plain = s => String(s ?? '').normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/ς/g, 'σ');
const accentedIota = w => /ί/.test(w.normalize('NFC').slice(-2));   // «μπαταρία» (θηλ.) ≠ «ράφια» (ουδ. πληθ.)
// Αρσενικά σε -ες στον πληθυντικό (οι σωλήνες → τους σωλήνες): ρίζες που η κατάληξη δεν ξεχωρίζει από τα θηλυκά.
const MASC_PLURAL = ['σωλην', 'διακοπτ', 'καθρεπτ', 'καθρεφτ', 'θερμοστατ', 'ανεμιστηρ', 'αισθητηρ', 'συλλεκτ', 'κυκλοφορητ', 'εξαεριστηρ',
  'μεντεσεδ', 'προβολ', 'καυστηρ', 'αγωγ', 'τοιχ', 'σωληνωτ', 'θερμοσιφων', 'καναλ'];
// Εξαιρέσεις όπου η κατάληξη λέει άλλο γένος (λίστα που μεγαλώνει από τη λίστα της ομάδας).
const EXCEPT = {οδοσ: 'την', μεθοδοσ: 'την', εισοδοσ: 'την', εξοδοσ: 'την', καφεσ: 'τον', πλακακι: 'το', καγκελα: 'τα', παραθυρα: 'τα', επιπλα: 'τα', σκαλα: 'τη'};

/** Το όνομα όπως θα μπει στο κείμενο: πρώτο γράμμα μικρό (εκτός από ακρωνύμια), χωρίς κενά στις άκρες. */
export function cleanName(name){
  const t = String(name ?? '').trim().replace(/\s+/g, ' ');
  return t.length > 1 && t[1] === t[1].toLowerCase() ? t[0].toLowerCase() + t.slice(1) : t;
}

/** Το άρθρο που μαντεύουμε για ένα όνομα. */
export function guessArticle(name){
  const first = cleanName(name).split(' ')[0] || '', w = plain(first);
  if(EXCEPT[w]) return EXCEPT[w] === 'τη' ? 'την' : EXCEPT[w];
  if(!/[α-ω]/.test(w)) return 'το';                                   // ξένη λέξη («laminate», «inverter»)
  if(/εισ$/.test(w) || /ουσ$/.test(w)) return 'τους';
  if(/εσ$/.test(w)) return MASC_PLURAL.some(s => w.startsWith(s)) ? 'τους' : 'τις';
  if(/(ασ|ησ|οσ)$/.test(w)) return 'τον';
  if(/ματα$/.test(w)) return 'τα';
  if(/μα$/.test(w)) return 'το';
  if(/ια$/.test(w) && !accentedIota(first)) return 'τα';
  if(/(α|η)$/.test(w)) return 'την';
  if(/(ο|ι|μα|ον|υ)$/.test(w)) return 'το';
  return 'το';
}

/** «άρθρο + όνομα» σε αιτιατική: στο «τον» το τελικό -ς της πρώτης λέξης φεύγει («τον θερμοσίφωνα», «τον τοίχο»). */
export function withArticle(name, article = guessArticle(name)){
  const words = cleanName(name).split(' ');
  if(article === 'τον'){
    // -ος → -ο, -ας → -α, -ης → -η: αρκεί το κόψιμο του -ς. Στην πρώτη λέξη πάντα· στις επόμενες μόνο τα επίθετα
    // σε -ος («ηλιακός» → «ηλιακό»), όχι μετά από «της/του» («της κουζίνας» μένει).
    words.forEach((w, i) => {
      const p = plain(w), prev = plain(words[i - 1] || '');
      if(w.length > 2 && (i === 0 ? /(ασ|ησ|οσ)$/.test(p) : /οσ$/.test(p) && !['τησ', 'του', 'των'].includes(prev))) words[i] = w.slice(0, -1);
    });
  }
  // «την» χάνει το -ν πριν από σύμφωνο εκτός κ, π, τ, ξ, ψ, μπ, ντ, γκ, τσ, τζ (όπως «τη λεκάνη» στον χάρτη)· το «τον» μένει.
  const p = plain(words[0]);
  const keepN = /^[αεηιουωκπτξψ]/.test(p) || /^(μπ|ντ|γκ|τσ|τζ)/.test(p) || !/^[α-ω]/.test(p);
  return `${article === 'την' && !keepN ? 'τη' : article === 'τη' ? 'τη' : article} ${words.join(' ')}`;
}

/** Το κείμενο μιας γενικής κατηγορίας με το {είδος} μέσα. */
export const fillKind = (text, name, article) => String(text).replaceAll('{είδος}', withArticle(name, article));
